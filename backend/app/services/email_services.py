import random
import string
from datetime import datetime, timedelta, timezone
from typing import Optional

import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from email.mime.application import MIMEApplication
from app.config import settings


def generate_otp() -> str:
    return "".join(random.choices(string.digits, k=6))


def get_otp_expiry() -> datetime:
    return datetime.now(timezone.utc) + timedelta(minutes=10)


def send_otp_email(to_email: str, otp_code: str):
    if not settings.GMAIL_ADDRESS or not settings.GMAIL_APP_PASSWORD:
        print("[INFO] Gmail credentials not configured; skipping OTP email dispatch.")
        return

    subject = "Verify your VERIFACT account"
    body = f"""
    <html>
      <body style="font-family: sans-serif; color: #1e293b;">
        <h2 style="color: #0284c7;">Verify your VERIFACT Account</h2>
        <p>Your one-time clinical verification OTP code is:</p>
        <p style="font-size: 24px; font-weight: bold; letter-spacing: 4px; color: #0369a1;">{otp_code}</p>
        <p>This code expires in 10 minutes.</p>
        <hr style="border: 0; border-top: 1px solid #e2e8f0;"/>
        <p style="font-size: 11px; color: #64748b;">VERIFACT Clinical AI Co-Pilot System</p>
      </body>
    </html>
    """

    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"] = settings.GMAIL_ADDRESS
    msg["To"] = to_email
    msg.attach(MIMEText(body, "html"))

    try:
        with smtplib.SMTP("smtp.gmail.com", 587, timeout=4) as server:
            server.starttls()
            server.login(settings.GMAIL_ADDRESS, settings.GMAIL_APP_PASSWORD)
            server.sendmail(settings.GMAIL_ADDRESS, to_email, msg.as_string())
    except Exception as e:
        print(f"[WARN] Failed to send OTP email: {e}")


def send_clinical_report_email(
    to_email: str,
    analysis_id: int,
    scan_bone: str,
    severity: str,
    report_text: str,
    doctor_name: Optional[str],
    pdf_bytes: bytes,
    patient_id: Optional[str] = None,
    notes: Optional[str] = None
) -> bool:
    """
    Sends the digitally verified radiology report and PDF attachment
    to referring trauma surgeons or patient records.
    """
    if not settings.GMAIL_ADDRESS or not settings.GMAIL_APP_PASSWORD:
        print("[INFO] Gmail credentials not configured; simulation mode enabled for report dispatch.")
        return True

    scan_label = f"FRX-{analysis_id:06d}"
    subject = f"Clinical Radiology Report: {scan_bone} ({scan_label})"

    signer = doctor_name or "Attending Orthopedic Specialist"
    patient_str = f"Patient ID: <strong>{patient_id}</strong><br/>" if patient_id else ""
    notes_html = f"<div style='margin-top: 15px; padding: 10px; background: #f8fafc; border-left: 3px solid #0284c7;'><strong>Clinical Note:</strong> {notes}</div>" if notes else ""

    html_content = f"""
    <html>
      <body style="font-family: Arial, sans-serif; color: #1e293b; line-height: 1.6; max-width: 600px; margin: auto; padding: 20px;">
        <div style="border-bottom: 2px solid #0284c7; padding-bottom: 12px; margin-bottom: 20px;">
          <h2 style="margin: 0; color: #0f172a;">VERIFACT Radiology Co-Pilot</h2>
          <span style="font-size: 12px; color: #64748b;">Emergency Trauma Triage & Musculoskeletal Report</span>
        </div>

        <p>A verified clinical radiograph report has been issued for <strong>{scan_label}</strong>:</p>

        <div style="background: #f1f5f9; padding: 15px; border-radius: 8px; margin: 15px 0;">
          {patient_str}
          Anatomical Region: <strong>{scan_bone}</strong><br/>
          Clinical Severity: <strong>{severity}</strong><br/>
          Physician Signer: <strong>{signer}</strong>
        </div>

        <h4 style="color: #0f172a; margin-bottom: 6px;">Synthesized Radiology Findings:</h4>
        <p style="background: #ffffff; border: 1px solid #cbd5e1; padding: 12px; border-radius: 6px; font-style: italic;">
          "{report_text}"
        </p>

        {notes_html}

        <p style="margin-top: 20px;">The official, signed PDF document with complete legal stamp is attached.</p>

        <hr style="border: 0; border-top: 1px solid #e2e8f0; margin-top: 30px;"/>
        <p style="font-size: 11px; color: #94a3b8; text-align: center;">
          CONFIDENTIAL MEDICAL RECORD • Generated by VERIFACT HL7/HIPAA Compliant System
        </p>
      </body>
    </html>
    """

    msg = MIMEMultipart()
    msg["Subject"] = subject
    msg["From"] = settings.GMAIL_ADDRESS
    msg["To"] = to_email
    msg.attach(MIMEText(html_content, "html"))

    # Attach the signed PDF document
    pdf_attachment = MIMEApplication(pdf_bytes, _subtype="pdf")
    pdf_attachment.add_header(
        "Content-Disposition",
        "attachment",
        filename=f"VERIFACT_Report_{scan_label}.pdf"
    )
    msg.attach(pdf_attachment)

    try:
        with smtplib.SMTP("smtp.gmail.com", 587, timeout=6) as server:
            server.starttls()
            server.login(settings.GMAIL_ADDRESS, settings.GMAIL_APP_PASSWORD)
            server.sendmail(settings.GMAIL_ADDRESS, to_email, msg.as_string())
        return True
    except Exception as e:
        print(f"[WARN] Failed to send report email: {e}")
        return False
